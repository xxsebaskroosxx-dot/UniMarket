create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  username text not null,
  full_name text not null,
  role text not null default 'user' check (role in ('admin', 'user')),
  created_at timestamptz not null default now()
);

create table public.products (
  id bigint generated by default as identity primary key,
  owner_id uuid not null references public.profiles (id) on delete cascade,
  name text not null,
  price numeric(12, 2) not null check (price > 0),
  category text not null,
  emoji text not null default '📦',
  state text not null default 'Publicado',
  images text[] not null default '{}',
  description text,
  created_at timestamptz not null default now()
);

create table public.conversations (
  id uuid primary key default gen_random_uuid(),
  participant_one uuid not null references public.profiles (id) on delete cascade,
  participant_two uuid not null references public.profiles (id) on delete cascade,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint conversations_distinct_participants check (participant_one < participant_two),
  constraint conversations_unique_pair unique (participant_one, participant_two)
);

create table public.messages (
  id uuid primary key default gen_random_uuid(),
  conversation_id uuid not null references public.conversations (id) on delete cascade,
  sender_id uuid not null references public.profiles (id) on delete cascade,
  content text not null check (char_length(trim(content)) between 1 and 4000),
  created_at timestamptz not null default now()
);

create index products_created_at_idx on public.products (created_at desc);
create unique index profiles_username_lower_idx on public.profiles (lower(username));
create index conversations_participants_idx on public.conversations (participant_one, participant_two);
create index messages_conversation_created_at_idx on public.messages (conversation_id, created_at);

create function public.create_profile_for_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, username, full_name)
  values (
    new.id,
    trim(new.raw_user_meta_data ->> 'username'),
    trim(new.raw_user_meta_data ->> 'full_name')
  );
  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.create_profile_for_new_user();

create function public.update_conversation_timestamp()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  update public.conversations
  set updated_at = new.created_at
  where id = new.conversation_id;
  return new;
end;
$$;

create trigger on_message_created
  after insert on public.messages
  for each row execute procedure public.update_conversation_timestamp();

create function public.get_or_create_conversation(other_user_id uuid)
returns uuid
language plpgsql
security invoker
set search_path = ''
as $$
declare
  current_user_id uuid := auth.uid();
  conversation_id uuid;
begin
  if current_user_id is null or current_user_id = other_user_id then
    raise exception 'A valid other user is required';
  end if;

  insert into public.conversations (participant_one, participant_two)
  values (least(current_user_id, other_user_id), greatest(current_user_id, other_user_id))
  on conflict (participant_one, participant_two)
  do update set updated_at = public.conversations.updated_at
  returning id into conversation_id;

  return conversation_id;
end;
$$;

