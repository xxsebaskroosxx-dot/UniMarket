create policy "Authenticated users can read profiles"
  on public.profiles for select to authenticated using (true);

create function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.profiles
    where id = auth.uid() and role = 'admin'
  );
$$;

grant execute on function public.is_admin() to authenticated;

create policy "Admins can update any product"
  on public.products for update to authenticated
  using (public.is_admin()) with check (public.is_admin());
create policy "Admins can delete any product"
  on public.products for delete to authenticated
  using (public.is_admin());

create policy "Authenticated users can read products"
  on public.products for select to authenticated using (true);
create policy "Users can publish their own products"
  on public.products for insert to authenticated with check (auth.uid() = owner_id);
create policy "Users can update their own products"
  on public.products for update to authenticated using (auth.uid() = owner_id) with check (auth.uid() = owner_id);
create policy "Users can delete their own products"
  on public.products for delete to authenticated using (auth.uid() = owner_id);

create policy "Conversation participants can read conversations"
  on public.conversations for select to authenticated
  using (auth.uid() = participant_one or auth.uid() = participant_two);
create policy "Conversation participants can create conversations"
  on public.conversations for insert to authenticated
  with check (auth.uid() = participant_one or auth.uid() = participant_two);
create policy "Conversation participants can update conversations"
  on public.conversations for update to authenticated
  using (auth.uid() = participant_one or auth.uid() = participant_two)
  with check (auth.uid() = participant_one or auth.uid() = participant_two);

create policy "Conversation participants can read messages"
  on public.messages for select to authenticated
  using (exists (
    select 1 from public.conversations c
    where c.id = conversation_id and (auth.uid() = c.participant_one or auth.uid() = c.participant_two)
  ));
create policy "Participants can send messages as themselves"
  on public.messages for insert to authenticated
  with check (
    auth.uid() = sender_id
    and exists (
      select 1 from public.conversations c
      where c.id = conversation_id and (auth.uid() = c.participant_one or auth.uid() = c.participant_two)
    )
  );

